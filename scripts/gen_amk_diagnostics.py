"""Generates AmkDiagnostics.hpp / .cpp from the index of the AMK PDK_025786 documentation.

Usage:
    python scripts/gen_amk_diagnostics.py

Downloads the TOC of the AMKmotion documentation and extracts the full
"diagnostic number -> description" list. It is the same list used by the ECU
firmware (source/powertrain_control/inverter/INVERTER_Errors.h): if AMK
publishes a new version of the document, run both scripts again.

Warning: the two generated C++ files are OVERWRITTEN entirely, comments
included. To change the documentation of AmkDiagnostics.hpp/.cpp edit the
texts below (HEADER and the comment lines in gen_cpp), not the generated files.
"""
import os
import re
import urllib.request

# Index (TOC) of the AMK online documentation: it contains the "<code> <description>" titles
TOC_URL = ('https://doku.amk-motion.com/en/Subsystems/PDK_025786_Diagnose/'
           'Data/Tocs/PDK_025786_Diagnose_Chunk0.js')

# Paths of the generated files, relative to the repository root
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HPP_PATH = os.path.join(REPO_ROOT, 'include', 'Telemetry', 'data_acquisition', 'AmkDiagnostics.hpp')
CPP_PATH = os.path.join(REPO_ROOT, 'src', 'Telemetry', 'data_acquisition', 'AmkDiagnostics.cpp')

# Backslash character, used to build the regex for the TOC \uXXXX escapes
BS = chr(92)

# Code ranges per functional group (from PDK_025786): (first, last, name)
GROUPS = [
    (257, 260, 'CONTROL_PANEL'),
    (512, 525, 'MONITOR'),
    (768, 799, 'DATABASE'),
    (1024, 1120, 'CENTRAL_COMPUTER'),
    (1280, 1460, 'PARAMETER'),
    (1536, 1559, 'EEPROM'),
    (1792, 1849, 'DRIVE_COMMANDING'),
    (2048, 2079, 'SBUS'),
    (2304, 2370, 'INVERTER_HW'),
    (2560, 2599, 'SERCOS'),
    (2600, 2619, 'PROFIBUS'),
    (2620, 2629, 'ARCNET'),
    (2640, 2649, 'LON'),
    (2660, 2669, 'INTERBUS'),
    (2680, 2699, 'CAN'),
    (2720, 2739, 'ETHERCAT'),
    (2740, 2749, 'MODBUS'),
    (2760, 2764, 'COE'),
    (2816, 2819, 'OPTION_PS'),
    (3071, 3079, 'OPTION_SERCOS'),
    (3328, 3328, 'OPTION_NC'),
    (3584, 3603, 'SPECIAL_FUNCTIONS'),
    (3605, 3610, 'FUNCTIONAL_SAFETY'),
    (3840, 3871, 'OPERATING_SYSTEM'),
]


def unescape(s):
    """Converts the \\uXXXX sequences (even with multiple backslashes) to the Unicode character."""
    return re.sub((BS * 2) + '+u([0-9a-fA-F]{4})',
                  lambda m: chr(int(m.group(1), 16)), s)


def load_rows():
    """Downloads the TOC and returns the sorted list [(code, description), ...]."""
    with urllib.request.urlopen(TOC_URL) as response:
        text = response.read().decode('utf-8')
    pairs = re.findall(r"'(/Content/[^']+)':{i:\[\d+\],t:\['([^']*)'\]", text)
    rows = []
    for _path, title in pairs:
        title = unescape(title).replace('\xa0', ' ').strip().strip("'").strip()
        m = re.match(r'^(\d+)\s+(.*)$', title)
        if m:
            # a comma would break the CSV, a double quote the C++ string
            name = m.group(2).strip().strip("'").strip()
            name = name.replace(',', ' -').replace('"', "'")
            rows.append((int(m.group(1)), ' '.join(name.split())))
    rows.sort()
    assert len({c for c, _ in rows}) == len(rows), 'duplicate codes'
    return rows


# Full content of AmkDiagnostics.hpp (written as is)
HEADER = '''/**
 * @file AmkDiagnostics.hpp
 * @brief Decoding of the AMK inverter diagnostic numbers.
 *
 * @details
 * AMK diagnostic numbers (AMK_ActualErrorInfo) sent by the ECU in the
 * inv_L_errorInfo / inv_R_errorInfo fields of packet 0xCC. They are the same
 * numbers shown on the inverter display, documented by AMKmotion in PDK_025786
 * "Diagnosis messages": https://doku.amk-motion.com/en/Subsystems/PDK_025786_Diagnose/
 *
 * Used by TelemetrySchema (ValueFormat::InverterDiag) to convert the number to
 * text and back, and by InverterDataWindow to colour the diagnostic.
 *
 * @warning File generated by scripts/gen_amk_diagnostics.py: do not edit by hand
 *          (not even the comments, which must be changed in the script).
 */

#pragma once

#include <cstdint>
#include <string>

/**
 * @brief Text description of a diagnostic code.
 * @param code AMK diagnostic number.
 * @return Description, or nullptr if the code is not listed.
 */
const char* amkDiagName(uint16_t code);

/**
 * @brief Functional group of the code (INVERTER_HW, CAN, FUNCTIONAL_SAFETY, ...).
 * @param code AMK diagnostic number.
 * @return Group name, "NONE" for 0, "UNKNOWN" if outside every known range.
 */
const char* amkDiagGroupName(uint16_t code);

/**
 * @brief Tells whether AMK classifies the code as a "warning" (it does not stop the drive).
 * @param code AMK diagnostic number.
 * @return true for warnings, false for actual errors.
 */
bool amkDiagIsWarning(uint16_t code);

/**
 * @brief Text shown in the UI and written to CSVs, e.g. "2347 INVERTER_HW Motor temperature error".
 * @param code AMK diagnostic number.
 * @return Text "<code> <group> <description>"; code 0 becomes "NO_DIAG".
 */
std::string amkDiagToText(uint16_t code);

/**
 * @brief Exact inverse of amkDiagToText(), to read a saved CSV back.
 * @param text Text produced by amkDiagToText() (or a plain number).
 * @return Diagnostic number (0 for empty text or "NO_DIAG").
 */
uint16_t amkDiagFromText(const char* text);
'''


def gen_cpp(rows):
    """Returns the full content of AmkDiagnostics.cpp for the given rows."""
    L = []
    a = L.append
    a('/**')
    a(' * @file AmkDiagnostics.cpp')
    a(' * @brief AMK diagnostic code tables and conversion functions (see AmkDiagnostics.hpp).')
    a(' *')
    a(' * @warning File generated by scripts/gen_amk_diagnostics.py: do not edit by hand.')
    a(' */')
    a('')
    a('#include "Telemetry/data_acquisition/AmkDiagnostics.hpp"')
    a('')
    a('#include <algorithm>')
    a('#include <cstdlib>')
    a('#include <cstring>')
    a('')
    a('namespace {')
    a('')
    a('/// One table entry: diagnostic number and AMK description.')
    a('struct DiagEntry { uint16_t code; const char* name; };')
    a('')
    a('/// All known diagnostics, sorted by code: lookup is a binary search.')
    a('const DiagEntry kDiagnostics[] = {')
    for code, title in rows:
        a('    { %5dU, "%s" },' % (code, title))
    a('};')
    a('')
    a('/// Range of codes [lo, hi] belonging to a functional group.')
    a('struct DiagGroup { uint16_t lo; uint16_t hi; const char* name; };')
    a('')
    a('/// Functional groups defined by AMK in PDK_025786.')
    a('const DiagGroup kGroups[] = {')
    for lo, hi, tag in GROUPS:
        a('    { %5dU, %5dU, "%s" },' % (lo, hi, tag))
    a('};')
    a('')
    warnings = sorted({c for c, t in rows if 'warning' in t.lower()})
    a('/// Diagnostics marked as "warning" by AMK ("Message classes", PDK_025786).')
    a('const uint16_t kWarnings[] = {')
    a('    ' + ', '.join('%dU' % c for c in warnings))
    a('};')
    a('')
    a('} // namespace')
    a('')
    a('const char* amkDiagName(uint16_t code) {')
    a('    const auto* begin = std::begin(kDiagnostics);')
    a('    const auto* end   = std::end(kDiagnostics);')
    a('    const auto* it = std::lower_bound(begin, end, code,')
    a('        [](const DiagEntry& entry, uint16_t value) { return entry.code < value; });')
    a('    return (it != end && it->code == code) ? it->name : nullptr;')
    a('}')
    a('')
    a('const char* amkDiagGroupName(uint16_t code) {')
    a('    if (code == 0U) return "NONE";')
    a('    for (const auto& group : kGroups) {')
    a('        if (code >= group.lo && code <= group.hi) return group.name;')
    a('    }')
    a('    return "UNKNOWN";')
    a('}')
    a('')
    a('bool amkDiagIsWarning(uint16_t code) {')
    a('    for (const uint16_t warning : kWarnings) {')
    a('        if (warning == code) return true;')
    a('    }')
    a('    return false;')
    a('}')
    a('')
    a('std::string amkDiagToText(uint16_t code) {')
    a('    if (code == 0U) return "NO_DIAG";')
    a('')
    a('    std::string text = std::to_string(code);')
    a('    text += \' \';')
    a('    text += amkDiagGroupName(code);')
    a('    text += \' \';')
    a('')
    a('    const char* name = amkDiagName(code);')
    a('    text += (name != nullptr) ? name : "see PDK_025786";')
    a('    return text;')
    a('}')
    a('')
    a('uint16_t amkDiagFromText(const char* text) {')
    a('    // The text always starts with the number, so parsing it back is enough')
    a('    if (text == nullptr || *text == \'\\0\') return 0U;')
    a('    return static_cast<uint16_t>(std::atoi(text));')
    a('}')
    return '\n'.join(L) + '\n'


def main():
    """Downloads the up-to-date list and rewrites the two C++ files."""
    rows = load_rows()
    with open(HPP_PATH, 'w', encoding='utf-8', newline='\n') as f:
        f.write(HEADER)
    with open(CPP_PATH, 'w', encoding='utf-8', newline='\n') as f:
        f.write(gen_cpp(rows))
    print('codes: %d' % len(rows))


if __name__ == '__main__':
    main()
